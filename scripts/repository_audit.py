"""Maintain documentation catalogues and check stored publication integrity.

These checks do not reproduce numerical training or authenticate TPM evidence.
Only the ``index`` operation writes the two declared catalogue files.
"""
from __future__ import annotations

import argparse
from collections import defaultdict
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import sys
import unicodedata
from urllib.parse import unquote, urlsplit

SKIP = {'.git', '.venv', '.pytest_cache', '.ruff_cache', '__pycache__',
        'node_modules', 'data'}


def sha256(path: Path) -> str:
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def without_fences(text: str) -> str:
    lines = []
    fence = None
    for line in text.splitlines():
        match = re.match(r'^\s*(`{3,}|~{3,})', line)
        if match:
            token = match.group(1)[0]
            if fence is None:
                fence = token
            elif fence == token:
                fence = None
            continue
        if fence is None:
            lines.append(line)
    return '\n'.join(lines)


def headings(text: str) -> set[str]:
    counts: dict[str, int] = defaultdict(int)
    result = set()
    for line in without_fences(text).splitlines():
        match = re.match(r'^#{1,6}\s+(.+?)\s*#*$', line)
        if not match:
            continue
        title = unicodedata.normalize('NFKC', match.group(1)).lower()
        slug = re.sub(r'[^\w\- ]', '', title).replace(' ', '-')
        number = counts[slug]
        counts[slug] += 1
        result.add(f'{slug}-{number}' if number else slug)
    return result


def link_findings(path: Path) -> list[dict[str, str]]:
    result = []
    for match in re.finditer(r'!?\[[^\]\n]*\]\(([^)\n]+)\)',
                             without_fences(path.read_text(encoding='utf-8'))):
        raw = match.group(1).strip()
        target = raw[1:raw.index('>')] if raw.startswith('<') and '>' in raw else raw.split(' "')[0]
        url = urlsplit(target)
        if url.scheme or url.netloc:
            continue  # External links are not fetched by a local documentation check.
        local = path.parent / unquote(url.path) if url.path else path
        reason = None
        if not local.exists():
            reason = 'local_target_missing'
        elif url.fragment and local.suffix.lower() == '.md':
            if unquote(url.fragment) not in headings(local.read_text(encoding='utf-8')):
                reason = 'local_heading_missing'
        if reason:
            result.append(dict(target=target, reason=reason))
    return result


def owned_markdown(root: Path):
    for folder, dirs, names in os.walk(root):
        dirs[:] = [d for d in dirs if d not in SKIP]
        for name in names:
            path = Path(folder) / name
            if path.suffix.lower() == '.md' and not path.is_symlink():
                yield path


# Study directories are grouped by theme one level below results/.
RESULT_THEMES = frozenset({"milestones", "admission", "gates-probes", "chain-witness", "external-data", "records"})


def read_map(root: Path) -> dict:
    mapping = json.loads((root / 'docs/documentation-map.json').read_text(encoding='utf-8'))
    if mapping['schema_version'] != 1:
        raise ValueError('Unsupported documentation map version')
    return mapping


def catalogues(mapping: dict) -> dict[str, str]:
    refs = ['# Versioned technical references', '',
            f"Catalogue reviewed: **{mapping['reviewed']}**. Generated by `make docs-index`.", '',
            'These documents retain their original profile, source release and execution',
            'history. The [maintained guide](README.md) and [status](STATUS.md) provide',
            'the current interpretation. A historical status or test count applies to its',
            'named release; the reference files are not rewritten by consolidation.', '']
    grouped = defaultdict(list)
    for item in mapping['references']:
        grouped[item['group']].append(item)
    for group, items in sorted(grouped.items()):
        refs += [f'## {group}', '', '| Reference | Role |', '| --- | --- |']
        for item in sorted(items, key=lambda x: x['path']):
            link = os.path.relpath(item['path'], 'docs')
            title = item['title'].replace('|', '\\|')
            refs.append(f"| [{title}]({link}) | Stable versioned reference |")
        refs.append('')
    studies = ['# Retained study catalogue', '',
               f"Catalogue reviewed: **{mapping['reviewed']}**. Generated by `make docs-index`.", '',
               'The [results overview](README.md) provides a shorter reading path.',
               'Entries register local retained directories, including negative and incomplete',
               'work. They do not certify Git tracking, public sanitization or defense success.',
               'A flat checksum index supports `make evidence-check STUDY=results/<study>`;',
               'other profiles retain their own signed manifests and verifiers.', '']
    grouped.clear()
    for item in mapping['studies']:
        grouped[item['group']].append(item)
    for group, items in sorted(grouped.items()):
        studies += [f'## {group}', '', '| Study | Reading scope | Flat checksum index |',
                    '| --- | --- | --- |']
        for item in sorted(items, key=lambda x: x['path']):
            path = item['path'] + ('/' + item['entry'] if item['entry'] else '/')
            label = Path(item['path']).name
            link = os.path.relpath(path, 'results')
            scope = item['scope'].replace('|', '\\|')
            flat = 'Available' if item['flat_checksum_index'] else 'Profile-specific evidence'
            studies.append(f'| [{label}]({link}) | {scope} | {flat} |')
        studies.append('')
    return {'docs/REFERENCE_INDEX.md': '\n'.join(refs), 'results/CATALOG.md': '\n'.join(studies)}


def audit(root: Path, mapping: dict, scan_runtime: bool = False) -> dict:
    errors = []
    maintained = set(mapping['maintained_pages']) | set(mapping['generated_pages'])
    references = {x['path'] for x in mapping['references']}
    expected_docs = {p for p in maintained | references if p.startswith('docs/')}
    actual_docs = {str(p.relative_to(root)) for p in (root / 'docs').rglob('*.md')}
    if actual_docs != expected_docs:
        errors.append(dict(kind='documentation_registration',
                           unregistered=sorted(actual_docs - expected_docs),
                           missing=sorted(expected_docs - actual_docs)))
    expected_studies = {x['path'] for x in mapping['studies']}
    actual_studies = set()
    for p in (root / 'results').iterdir():
        if not p.is_dir():
            continue
        children = [c for c in p.iterdir() if c.is_dir()] if p.name in RESULT_THEMES else [p]
        actual_studies |= {str(c.relative_to(root)) for c in children}
    if actual_studies != expected_studies:
        errors.append(dict(kind='study_registration', unregistered=sorted(actual_studies - expected_studies),
                           missing=sorted(expected_studies - actual_studies)))
    for rel, expected in mapping['protected_markdown_sha256'].items():
        path = root / rel
        if not path.is_file() or sha256(path) != expected:
            errors.append(dict(kind='retained_markdown_changed_or_missing', path=rel))
    for rel, expected in catalogues(mapping).items():
        path = root / rel
        if not path.is_file() or path.read_text(encoding='utf-8') != expected:
            errors.append(dict(kind='catalogue_stale', path=rel))
    historical = []
    count = 0
    if scan_runtime:
        candidates = set(owned_markdown(root))
    else:
        # Retained runtime pages are checked by their recorded paths, avoiding a
        # repeated walk through unrelated model/TPM/workspace payload trees.
        candidates = {root / rel for rel in mapping['protected_markdown_sha256']}
        candidates.update(owned_markdown(root / 'docs'))
        candidates.update(owned_markdown(root / 'results'))
        candidates.update(root.glob('*.md'))
    for path in sorted(candidates):
        if not path.is_file():
            continue  # Missing retained files are already reported above.
        count += 1
        rel = str(path.relative_to(root))
        findings = [dict(path=rel, **x) for x in link_findings(path)]
        if rel in maintained:
            errors.extend(dict(kind='maintained_link', **x) for x in findings)
            prose = without_fences(path.read_text(encoding='utf-8'))
            # Code identifiers and literal policy paths are excluded from prose checks.
            prose = re.sub(r'`[^`]*`', '', prose)
            personal = re.search(r'\b(?:we|our|you|your|I)\b', prose)
            if personal:
                errors.append(dict(kind='personal_register', path=rel, term=personal.group()))
        else:
            historical.extend(findings)
    return dict(status='passed' if not errors else 'failed', markdown_scanned=count,
                maintained_pages=len(maintained), versioned_references=len(references),
                study_directories=len(expected_studies),
                retained_markdown_checked=len(mapping['protected_markdown_sha256']),
                runtime_scan_performed=scan_runtime,
                errors=errors, historical_local_link_findings=historical,
                qualifications='Historical local-link findings are diagnostic; frozen files are not rewritten. '
                'External URLs are not fetched. This is not numerical replay or trust authentication.')


def check_evidence(root: Path, mapping: dict, study: str) -> dict:
    directory = (root / study).resolve()
    directory.relative_to((root / 'results').resolve())
    index = directory / 'file-checksums.json'
    expected = next((x['checksum_index_sha256'] for x in mapping['studies']
                     if (root / x['path']).resolve() == directory), None)
    if expected is None:
        raise ValueError('The selected study has no registered flat checksum index; use its profile verifier')
    if sha256(index) != expected:
        raise ValueError('Checksum index differs from the documentation catalogue reference')
    values = json.loads(index.read_text(encoding='utf-8'))
    if not isinstance(values, dict) or not values:
        raise ValueError('A nonempty flat checksum index is required')
    failures = []
    for rel, digest in values.items():
        if not isinstance(rel, str) or not isinstance(digest, str) or not re.fullmatch(r'[0-9a-f]{64}', digest):
            raise ValueError('Invalid flat checksum entry')
        if PurePosixPath(rel).is_absolute() or '..' in PurePosixPath(rel).parts:
            raise ValueError('Checksum path escapes the selected study')
        path = (directory / rel).resolve()
        path.relative_to(directory)
        if not path.is_file() or sha256(path) != digest:
            failures.append(rel)
    return dict(status='passed' if not failures else 'failed', study=str(directory.relative_to(root.resolve())),
                catalogued_index_matches=True, files_checked=len(values), failures=failures,
                fresh_numerical_replay=False, trust_authentication_checked=False,
                qualification='Stored file integrity against a local catalogue reference only.')


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('operation', choices=('docs', 'index', 'list', 'evidence'))
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--study', help='Registered results directory; defaults to the current V5 publication')
    parser.add_argument('--scan-runtime', action='store_true',
                        help='Also discover new Markdown throughout runtime artifact trees')
    parser.add_argument('--output', type=Path, help='Write a new JSON check report; existing files are refused')
    args = parser.parse_args(argv)
    try:
        root = args.root.resolve()
        mapping = read_map(root)
        if args.operation == 'index':
            for rel, text in catalogues(mapping).items():
                (root / rel).write_text(text, encoding='utf-8')
            print('Updated docs/REFERENCE_INDEX.md and results/CATALOG.md.')
            return 0
        if args.operation == 'list':
            for item in mapping['studies']:
                print(f"{item['path']}\t{item['entry'] or '(directory)'}\t{item['group']}")
            return 0
        report = audit(root, mapping, args.scan_runtime) if args.operation == 'docs' else check_evidence(
            root, mapping, args.study or mapping['default_study'])
        if args.output:
            with args.output.open('x', encoding='utf-8') as stream:
                json.dump(report, stream, indent=2)
                stream.write('\n')
        display = {k: v for k, v in report.items() if k != 'historical_local_link_findings'}
        if 'historical_local_link_findings' in report:
            display['historical_local_link_findings'] = len(report['historical_local_link_findings'])
        print(json.dumps(display, indent=2))
        return 0 if report['status'] == 'passed' else 1
    except (ValueError, OSError, KeyError, TypeError) as exc:
        print(f'Repository check failed: {exc}', file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
